// genskills compiles the repository's text Skill resources into reed.
package main

import (
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode/utf8"
)

func main() {
	root := "../../skills"
	entries, err := os.ReadDir(root)
	must(err)
	var source strings.Builder
	source.WriteString("// Code generated by go generate; DO NOT EDIT.\npackage skills\nvar resources = map[string]string{\n")
	count := 0
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		skill := filepath.Join(root, entry.Name())
		info, err := os.Stat(filepath.Join(skill, "SKILL.md"))
		if os.IsNotExist(err) {
			continue
		}
		must(err)
		if !info.Mode().IsRegular() {
			panic("invalid Skill entry: " + skill)
		}
		count++
		must(filepath.WalkDir(skill, func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			relative, err := filepath.Rel(skill, path)
			if err != nil {
				return err
			}
			if relative == "bin" && d.IsDir() {
				return filepath.SkipDir
			}
			if relative == "runtime.json" || relative == "bin" || d.IsDir() {
				return nil
			}
			info, err := d.Info()
			if err != nil {
				return err
			}
			if !info.Mode().IsRegular() {
				return fmt.Errorf("non-regular Skill source %q", path)
			}
			data, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if !utf8.Valid(data) || strings.ContainsRune(string(data), 0) {
				return fmt.Errorf("non-text Skill source %q", path)
			}
			fmt.Fprintf(&source, "%s: %s,\n", strconv.Quote(entry.Name()+"/"+filepath.ToSlash(relative)), strconv.Quote(string(data)))
			return nil
		}))
	}
	if count == 0 {
		panic("no Skills found; run from apps/reed")
	}
	source.WriteString("}\n")
	formatted, err := format.Source([]byte(source.String()))
	must(err)
	must(os.WriteFile("internal/skills/resources_gen.go", formatted, 0644))
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
